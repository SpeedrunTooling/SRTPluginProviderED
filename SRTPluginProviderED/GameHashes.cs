using System.IO;
using System.Linq;
using System.Security.Cryptography;

namespace SRTPluginProviderED
{
    public enum GameVersion : int
    {
        STEAM_July2024,
        STEAM_December2025,
        STEAM_May2026,
        UNKNOWN
    }

    public static class GameHashes
    {
        private static readonly byte[] eldenRingSteam2024July = new byte[32] { 0xB1, 0xB8, 0xBA, 0x8C, 0x8B, 0x5C, 0x68, 0x91, 0x88, 0xCA, 0x51, 0x1C, 0xDF, 0x12, 0xF4, 0x2B, 0x20, 0x78, 0x7C, 0x14, 0xA3, 0xC0, 0x6B, 0xA7, 0xCF, 0x81, 0x6D, 0x42, 0x37, 0x0C, 0x0A, 0x3C };
        private static readonly byte[] eldenringSteam2025December = new byte[32] { 0xFA, 0xFB, 0x93, 0x1F, 0x88, 0x6D, 0x5C, 0x8D, 0xAE, 0xBD, 0x93, 0xBA, 0x9E, 0xBA, 0xDE, 0x37, 0xC9, 0xA8, 0xD9, 0x55, 0x44, 0x76, 0x73, 0xB6, 0x5D, 0x45, 0x1F, 0x3A, 0xF1, 0x99, 0xE5, 0x45 };
        private static readonly byte[] eldenringSteam2026May = new byte[32] { 0x34, 0x10, 0x2B, 0x1C, 0x08, 0xBB, 0x5F, 0x76, 0x9A, 0x72, 0x44, 0x27, 0xA6, 0xF7, 0x0F, 0xE2, 0x9B, 0x3B, 0x73, 0x2C, 0x31, 0xCF, 0x73, 0x69, 0x3F, 0x86, 0x1C, 0x48, 0xD3, 0x49, 0x2D, 0xDB }; 
        public static GameVersion DetectVersion(string filePath)
        {
            byte[] checksum;
            using (SHA256 hashFunc = SHA256.Create())
            using (FileStream fs = new FileStream(filePath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete))
                checksum = hashFunc.ComputeHash(fs);

            if (checksum.SequenceEqual(eldenRingSteam2024July))
                return GameVersion.STEAM_July2024;
            else if (checksum.SequenceEqual(eldenringSteam2025December))
                return GameVersion.STEAM_December2025;
            else if (checksum.SequenceEqual(eldenringSteam2026May))
                return GameVersion.STEAM_May2026;
            else
                return GameVersion.UNKNOWN;
        }
    }
}